#include <stdio.h>

int main()
{
    int *p, ary[6] = {2, 4, 6, 8, 10, 12};
    p = ary;
    p += 2;
    p--; // 此时p=1
    //*和++都是从右往左结合
    // ！！p++是后缀自增：先返回p的值再增！！
    printf("%2d ", *p++);   // p=1，过后再变成p=2
    printf("%2d ", *(p++)); // 在上一条基础上，先返回p=2对应的值，再变成p=3
    printf("%2d ", (*p)++); // 先运行括号，p=3，即ary为8，()输出8后，再自增，是ary[3]自增1，ary[3]本身变成9！！
    printf("%2d ", *p++);   // p仍为3，ary[3]在上一条变成了9！！返回3后p再自增1
    printf("%2d ", *(++p)); // 此前p=4，由于++为前置，4再加1即为p的返回值，p=5
}